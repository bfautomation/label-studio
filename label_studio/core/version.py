""" Version Lib
Copyright (C) 2019 Maxim Tkachenko 

This library automatically generates version of package based on git.
If 'git desc' is successful it will write version to __version__.py:git_version.  
If 'git desc' is fail it will read __version__.py:git_version.

ATTENTION: do not include version_.py to git! It will affect git commit always!
"""
import json
import os
import re
from datetime import datetime, timezone
from importlib import util as importlib_util
from importlib.metadata import PackageNotFoundError
from importlib.metadata import version as package_version
from pathlib import Path
from subprocess import STDOUT, CalledProcessError
from subprocess import check_output as run

VERSION_FILE = 'version_.py'
LS_VERSION_FILE = 'ls-version_.py'
VERSION_OVERRIDE = os.getenv('VERSION_OVERRIDE', '')
BRANCH_OVERRIDE = os.getenv('BRANCH_OVERRIDE', '')
GIT_COMMIT_OVERRIDE = os.getenv('GIT_COMMIT', '')
GIT_BRANCH_OVERRIDE = os.getenv('GIT_BRANCH', '')
GIT_DATE_OVERRIDE = os.getenv('GIT_DATE', '')
GIT_MESSAGE_OVERRIDE = os.getenv('GIT_MESSAGE', '')


def _version_dir():
    return Path(os.path.dirname(__file__) or '.').resolve()


def _write_py(info):
    info_str = json.dumps(info)
    (_version_dir() / VERSION_FILE).write_text(
        'info = %s\n' % info_str + '\n# This file is automatically generated by version.py'
        '\n# Do not include it to git!\n'
    )


def _read_py(ls=False):
    # go to current dir to package __init__.py
    cwd = os.getcwd()
    d = str(_version_dir())
    os.chdir(d)

    def import_version_module(file_path):
        module_path = Path(d) / file_path
        if not module_path.exists():
            return None

        spec = importlib_util.spec_from_file_location(f'_generated_{module_path.stem}', module_path)
        if spec is None or spec.loader is None:
            return None

        module = importlib_util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module

    try:
        version_module = import_version_module(LS_VERSION_FILE if ls else VERSION_FILE)

        if not version_module and ls:
            version_module = import_version_module(VERSION_FILE)

        if version_module:
            return getattr(version_module, 'info', {})
        return {}
    except (ImportError, OSError, SyntaxError, AttributeError):
        return {}
    finally:
        os.chdir(cwd)  # back to current dir


def _package_version():
    # Source archives have no Git history; keep their declared release version.
    pyproject_path = _version_dir().parents[1] / 'pyproject.toml'
    try:
        pyproject = pyproject_path.read_text()
        project_section = re.search(r'(?ms)^\[project\]\s*$(.*?)(?=^\[|\Z)', pyproject)
        if project_section:
            declared = re.search(r"(?m)^version\s*=\s*['\"]([^'\"]+)['\"]", project_section.group(1))
            if declared:
                return declared.group(1)
    except OSError:
        pass
    try:
        return package_version('label-studio')
    except PackageNotFoundError:
        return '0.0.0+unknown'


def _fallback_info():
    version = VERSION_OVERRIDE or _package_version()
    git_commit, git_branch = _read_git_head_info()

    return {
        'message': GIT_MESSAGE_OVERRIDE if GIT_MESSAGE_OVERRIDE else 'Version metadata generated without git context',
        'commit': GIT_COMMIT_OVERRIDE if GIT_COMMIT_OVERRIDE else (git_commit if git_commit else 'unknown'),
        'date': GIT_DATE_OVERRIDE if GIT_DATE_OVERRIDE else datetime.now(timezone.utc).strftime('%Y/%m/%d %H:%M:%S'),
        'branch': BRANCH_OVERRIDE
        if BRANCH_OVERRIDE
        else (GIT_BRANCH_OVERRIDE if GIT_BRANCH_OVERRIDE else (git_branch if git_branch else 'unknown')),
        'version': version,
    }


def _has_fallback_overrides():
    return any(
        (
            VERSION_OVERRIDE,
            BRANCH_OVERRIDE,
            GIT_COMMIT_OVERRIDE,
            GIT_BRANCH_OVERRIDE,
            GIT_DATE_OVERRIDE,
            GIT_MESSAGE_OVERRIDE,
        )
    )


def _safe_write_py(info):
    try:
        _write_py(info)
    except OSError:
        pass


def _read_packed_ref(git_dir, ref_name):
    packed_refs_path = os.path.join(git_dir, 'packed-refs')
    try:
        with open(packed_refs_path) as packed_refs:
            for line in packed_refs:
                line = line.strip()
                if not line or line.startswith(('#', '^')):
                    continue
                commit, ref = line.split(' ', 1)
                if ref == ref_name:
                    return commit
    except OSError:
        return ''
    return ''


def _read_common_git_dir(git_dir):
    commondir_path = git_dir / 'commondir'
    if not commondir_path.exists():
        return git_dir

    try:
        common_git_dir = commondir_path.read_text().strip()
    except OSError:
        return git_dir

    resolved_common_git_dir = Path(common_git_dir)
    if not resolved_common_git_dir.is_absolute():
        resolved_common_git_dir = (git_dir / resolved_common_git_dir).resolve()
    return resolved_common_git_dir


def _find_git_dir():
    start_dir = _version_dir()
    candidates = (
        [Path(os.environ['GIT_DIR'])]
        if os.environ.get('GIT_DIR')
        else [parent / '.git' for parent in [start_dir, *start_dir.parents]]
    )
    for git_path in candidates:
        if git_path.is_dir():
            return git_path.resolve()
        if not git_path.is_file():
            continue
        try:
            git_ref = git_path.read_text().strip()
        except OSError:
            return None
        prefix = 'gitdir:'
        if not git_ref.lower().startswith(prefix):
            continue
        git_dir = Path(git_ref[len(prefix) :].strip())
        return git_dir if git_dir.is_absolute() else (git_path.parent / git_dir).resolve()
    return None


def _branch_name_from_ref(ref_name):
    prefix = 'refs/heads/'
    if ref_name.startswith(prefix):
        return ref_name[len(prefix) :]
    return ref_name.split('/', 1)[-1] if '/' in ref_name else ref_name


def _read_git_head_info():
    git_dir = _find_git_dir()
    if git_dir is None:
        return '', ''
    common_git_dir = _read_common_git_dir(git_dir)

    head_path = git_dir / 'HEAD'
    if not head_path.exists():
        return '', ''

    try:
        head_value = head_path.read_text().strip()
    except OSError:
        return '', ''

    if head_value.startswith('ref: '):
        ref_name = head_value.split(' ', 1)[1].strip()
        commit = ''
        for ref_root in (git_dir, common_git_dir):
            ref_path = ref_root / ref_name
            try:
                commit = ref_path.read_text().strip()
                if commit:
                    break
            except OSError:
                continue

        if not commit:
            commit = _read_packed_ref(str(git_dir), ref_name) or _read_packed_ref(str(common_git_dir), ref_name)

        branch = _branch_name_from_ref(ref_name)
        return commit, branch

    return head_value, ''


# get commit info: message, date, hash, branch
def get_git_commit_info(skip_os=True, ls=False):
    cwd = os.getcwd()
    d = str(_version_dir())
    os.chdir(d)

    try:
        # take version from git
        try:
            desc = run('git describe --long --tags --always --dirty', stderr=STDOUT, shell=True).decode('utf-8')
            info = {
                'message': run('git show -s --format=%s', stderr=STDOUT, shell=True).strip().decode('utf8'),
                'commit': run('git show -s --format=%H', stderr=STDOUT, shell=True).strip().decode('utf8'),
                'date': run('git log -1 --format="%cd" --date="format:%Y/%m/%d %H:%M:%S"', stderr=STDOUT, shell=True)
                .strip()
                .decode('utf8'),
                'branch': BRANCH_OVERRIDE
                if BRANCH_OVERRIDE
                else run(
                    "git branch --sort=committerdate -r --contains | grep -m 1 -v HEAD | cut -d'/' -f2-",
                    stderr=STDOUT,
                    shell=True,
                )
                .strip()
                .decode('utf8'),
            }
        except (CalledProcessError, OSError):
            os.chdir(cwd)
            info = _read_py(ls=ls) or _fallback_info()
            if _has_fallback_overrides():
                overrides = {
                    'version': VERSION_OVERRIDE,
                    'branch': BRANCH_OVERRIDE or GIT_BRANCH_OVERRIDE,
                    'commit': GIT_COMMIT_OVERRIDE,
                    'date': GIT_DATE_OVERRIDE,
                    'message': GIT_MESSAGE_OVERRIDE,
                }
                info.update({key: value for key, value in overrides.items() if value})
            _safe_write_py(info)
            return info

        # create package version
        version = desc.lstrip('v').rstrip().replace('-', '+', 1).replace('-', '.')
        # take OS name
        if not skip_os:
            keys = ('ID=', 'VERSION_ID=', 'RELEASE=')
            with open('/etc/os-release') as f:
                os_version = ''.join(
                    str(s).split('=', 1)[1].rstrip().strip('"').replace('.', '') for s in f if str(s).startswith(keys)
                )
                version += '.' + os_version
        info['version'] = VERSION_OVERRIDE if VERSION_OVERRIDE else version

        for key, value in (
            ('commit', GIT_COMMIT_OVERRIDE),
            ('branch', BRANCH_OVERRIDE or GIT_BRANCH_OVERRIDE),
            ('date', GIT_DATE_OVERRIDE),
            ('message', GIT_MESSAGE_OVERRIDE),
        ):
            if value:
                info[key] = value
        _safe_write_py(info)
        return info

    finally:
        os.chdir(cwd)  # back current dir


def get_git_version(skip_os=True):
    info = get_git_commit_info(skip_os)
    return info.get('version', '')


# get only tag from git
def get_short_version():
    version = get_git_version()
    return version.split('+')[0]


if __name__ == '__main__':
    # init version_.py file
    get_git_version()
